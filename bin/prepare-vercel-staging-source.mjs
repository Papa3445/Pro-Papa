// Prepare a minimal, deterministic Vercel staging source tree from a pinned checkout.
// This does NOT authenticate to Vercel, deploy, modify routing, or access secrets.
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {copyFileSync,existsSync,lstatSync,mkdirSync,readFileSync,writeFileSync} from 'node:fs';
import {dirname,isAbsolute,join,resolve,sep} from 'node:path';
import {fileURLToPath} from 'node:url';

export const STAGING_SOURCE_FILES=Object.freeze([
  'api/mcp.mjs',
  'bin/render-vercel-oauth-metadata.mjs',
  'package.json',
  'src/artifact-validation.mjs',
  'src/core.mjs',
  'src/execution-trace.mjs',
  'src/gateway.mjs',
  'src/iso-date.mjs',
  'src/mcp-call-provenance.mjs',
  'src/mcp-web.mjs',
  'src/memo.mjs',
  'src/oauth-resource.mjs',
  'src/planning.mjs',
  'src/reference-host.mjs',
  'src/review-github.mjs',
  'src/usage-receipts.mjs',
  'vercel.json',
]);

const SHA=/^[a-f0-9]{40}$/;
const digest=(name,bytes)=>createHash(name).update(bytes).digest('hex');

/** Copies only the audited runtime source list; never copies secrets or Netlify files. */
export function prepareVercelStagingSource({sourceRoot,outputDir,sourceCommit}){
  if(typeof sourceRoot!=='string'||!sourceRoot||typeof outputDir!=='string'||!outputDir||
    !SHA.test(sourceCommit??'')) throw Error('An exact source root, output directory, and 40-character commit SHA are required');
  const source=resolve(sourceRoot),target=resolve(outputDir);
  if(target===source||target.startsWith(source+sep))
    throw Error('The staging output must be outside the checkout');
  if(existsSync(target)) throw Error('The staging output directory must not already exist');
  const files=[];
  // Validate the entire source list before creating an output directory.
  for(const path of STAGING_SOURCE_FILES){
    const p=join(source,path),stat=lstatSync(p);
    if(!stat.isFile()||stat.isSymbolicLink())
      throw Error('Refusing non-regular or linked staging source: '+path);
    const bytes=readFileSync(p);
    files.push({path,size:bytes.length,sha1:digest('sha1',bytes),sha256:digest('sha256',bytes)});
  }
  mkdirSync(target,{recursive:false});
  for(const file of files){
    const dest=join(target,file.path);
    mkdirSync(dirname(dest),{recursive:true});
    copyFileSync(join(source,file.path),dest);
    if(digest('sha256',readFileSync(dest))!==file.sha256)
      throw Error('Copied staging source differs from pinned input: '+file.path);
  }
  const manifest={schemaVersion:1,sourceRepository:'Papa3445/Pro-Papa',
    sourceCommit,sourceFiles:files,
    generatedMetadata:'public/.well-known/oauth-protected-resource is generated by the Vercel build from host-managed OAuth environment settings',
    scope:'Staging source manifest only; not proof of deployed compiled function bytes or live rollback'};
  writeFileSync(join(target,'pro-papa-staging-source-manifest.json'),JSON.stringify(manifest,null,2)+'\n');
  return manifest;
}

function pinnedCleanCheckout(root){
  const git=(args)=>execFileSync('git',args,{cwd:root,encoding:'utf8'}).trim();
  const commit=git(['rev-parse','HEAD']);
  if(!SHA.test(commit)||git(['status','--porcelain','--untracked-files=no']))
    throw Error('Deploy preparation requires a clean, immutable Git checkout');
  return commit;
}

if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  try{
    const args=process.argv.slice(2);
    if(args.length!==4||args[0]!=='--commit'||args[2]!=='--output'||!isAbsolute(args[3]))
      throw Error('Usage: node bin/prepare-vercel-staging-source.mjs --commit <full-SHA> --output <absolute-directory-outside-checkout>');
    const root=process.cwd(),commit=pinnedCleanCheckout(root);
    if(commit!==args[1])throw Error('Pinned commit does not match checkout HEAD');
    const manifest=prepareVercelStagingSource({sourceRoot:root,outputDir:args[3],sourceCommit:commit});
    console.log(JSON.stringify({status:'prepared',sourceCommit:manifest.sourceCommit,
      outputDir:resolve(args[3]),sourceFiles:manifest.sourceFiles.length}));
  }catch(error){
    console.error('Staging source preparation rejected: '+error.message);
    process.exitCode=1;
  }
}
